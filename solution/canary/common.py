"""Shared by canaryctl and engine.py: paths, durable state, nginx control, status and events.

Durable (survives a reboot):  /var/lib/canary/state.json, nginx.conf, nginx temp dirs; /var/log/canary.
Volatile (lost on reboot):    /run/canary: status.json, nginx.pid, engine.pid.

Every decision is written to state.json (atomically, fsynced) BEFORE it is applied to nginx or
logged, so a crash at any point leaves state that recovery can finish: re-render nginx from state,
and log any decision event the crash cut off."""
import json, os, signal, subprocess, time

RUN, LOGDIR, LIB = "/run/canary", "/var/log/canary", "/var/lib/canary"
STATE, STATUS, EVENTS = f"{LIB}/state.json", f"{RUN}/status.json", f"{LOGDIR}/events.jsonl"
NGINX, NGINX_CONF, NGINX_PID = "/usr/sbin/nginx", f"{LIB}/nginx.conf", f"{RUN}/nginx.pid"
ACCESS_LOG, ERROR_LOG = f"{LOGDIR}/access.log", f"{LOGDIR}/nginx-error.log"
ENGINE_PID = f"{RUN}/engine.pid"
BLUE_ADDR, GREEN_ADDR = "127.0.0.1:9001", "127.0.0.1:9002"
STAGES = {1: (90, 10), 2: (50, 50), 3: (0, 100)}

def W(b, g): return {"app-blue": b, "app-green": g}

# ---------------------------------------------------------------- durable state
IDLE = {"rollout_id": None, "state": "idle", "stage": None, "dwell": None, "stage_entered_at": None,
        "abort_reason": None, "window": None}

def load_state():
    try:
        with open(STATE) as f: return {**IDLE, **json.load(f)}
    except (OSError, ValueError): return dict(IDLE)

def save_state(st):
    """Atomic and durable: write a temp file, fsync it, rename over, fsync the directory."""
    tmp = f"{STATE}.{os.getpid()}.tmp"
    with open(tmp, "w") as f:
        json.dump(st, f); f.flush(); os.fsync(f.fileno())
    os.replace(tmp, STATE)
    d = os.open(LIB, os.O_RDONLY)
    try: os.fsync(d)
    finally: os.close(d)

def desired_weights(st):
    if st["state"] == "shifting": return STAGES[st["stage"]]
    if st["state"] == "promoted": return (0, 100)
    return (100, 0)                                    # idle, aborted

# ---------------------------------------------------------------- nginx
def render_conf(blue, green):
    """The defaults that would hide a failing canary are all switched off explicitly:
    max_fails=0       nginx's passive health check would otherwise pull app-green out of rotation for
                      fail_timeout (10 s) after a single failure, silently changing the split and
                      starving the window of green requests;
    proxy_next_upstream off   a failed green request would otherwise be retried on blue, so the client
                      sees 200 and the log line ends with blue;
    proxy_read_timeout 5s     the default 60 s would hide a hung green past every deadline.
    A zero weight is not allowed by nginx, so that server is marked `down` instead."""
    def srv(addr, w): return f"server {addr} weight={w} max_fails=0;" if w else f"server {addr} down;"
    return f"""# generated by canaryctl/engine from {STATE}; do not edit
worker_processes 2;
pid {NGINX_PID};
error_log {ERROR_LOG} warn;
events {{ worker_connections 4096; }}
http {{
    client_body_temp_path {LIB}/nginx/client_body;
    proxy_temp_path       {LIB}/nginx/proxy;
    fastcgi_temp_path     {LIB}/nginx/fastcgi;
    uwsgi_temp_path       {LIB}/nginx/uwsgi;
    scgi_temp_path        {LIB}/nginx/scgi;
    log_format canary '$msec $upstream_addr $upstream_status $status';
    access_log {ACCESS_LOG} canary;
    upstream apps {{
        {srv(BLUE_ADDR, blue)}
        {srv(GREEN_ADDR, green)}
    }}
    server {{
        listen 127.0.0.1:8080;
        location / {{
            proxy_pass http://apps;
            proxy_next_upstream off;
            proxy_connect_timeout 1s;
            proxy_send_timeout 5s;
            proxy_read_timeout 5s;
            proxy_set_header Host $host;
        }}
    }}
}}
"""

def write_conf(blue, green):
    """Returns True if the file changed."""
    new = render_conf(blue, green)
    try:
        with open(NGINX_CONF) as f:
            if f.read() == new: return False
    except OSError: pass
    tmp = f"{NGINX_CONF}.tmp"
    with open(tmp, "w") as f: f.write(new)
    os.replace(tmp, NGINX_CONF)
    return True

def alive(pid, name):
    """Running and not a zombie: a killed process lingers as a zombie until PID 1 reaps it."""
    try:
        with open(f"/proc/{pid}/stat") as f: stat = f.read()
        return stat[stat.index("(") + 1:stat.rindex(")")] == name and stat[stat.rindex(")") + 2] not in "ZX"
    except (OSError, ValueError, IndexError): return False

def read_pid(path):
    try:
        with open(path) as f: return int(f.read().split()[0])
    except (OSError, ValueError, IndexError): return None

def nginx_pid():
    pid = read_pid(NGINX_PID)
    return pid if pid and alive(pid, "nginx") else None

def kill_stray_nginx(uid):
    """After a crash, orphaned workers can still hold :8080. Kill every nginx process of `uid`."""
    for p in filter(str.isdigit, os.listdir("/proc")):
        try:
            if os.stat(f"/proc/{p}").st_uid == uid and alive(int(p), "nginx"): os.kill(int(p), signal.SIGKILL)
        except OSError: pass

def start_nginx(prefix=()):
    """Start nginx (it daemonises itself: new session, no tty) and wait for its pid file."""
    subprocess.run([*prefix, NGINX, "-q", "-e", ERROR_LOG, "-c", NGINX_CONF], check=True, timeout=10,
                   stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for _ in range(50):
        if nginx_pid(): return True
        time.sleep(0.1)
    return False

def reload_nginx():
    """Graceful reload: new workers take the new split; old ones finish their requests."""
    pid = nginx_pid()
    if pid:
        os.kill(pid, signal.SIGHUP); time.sleep(0.15)
    return bool(pid)

def apply(st):
    """Render the state's split and reload nginx. Always reloads: the caller owns nginx right now."""
    write_conf(*desired_weights(st)); reload_nginx()

# ---------------------------------------------------------------- status and events
def write_status(status):
    tmp = f"{STATUS}.{os.getpid()}.tmp"
    with open(tmp, "w") as f: json.dump(status, f)
    os.replace(tmp, STATUS)

def status_from_state(st, pid=None):
    b, g = desired_weights(st)
    return {"rollout_id": st["rollout_id"], "state": st["state"], "stage": st["stage"], "weights": W(b, g),
            "pid": pid, "window": st["window"], "abort_reason": st["abort_reason"]}

def event(ev):
    ev = {"ts": round(time.time(), 3), **ev}
    with open(EVENTS, "a") as f: f.write(json.dumps(ev) + "\n")

def logged_events(rid):
    out = []
    try:
        with open(EVENTS) as f:
            for line in f:
                try: e = json.loads(line)
                except ValueError: continue
                if e.get("rollout_id") == rid: out.append(e)
    except OSError: pass
    return out

def reconcile_events(st):
    """Log any decision that state.json records but the event log lacks (the engine was killed
    between persisting a decision and logging it). Called before `resumed`, so each decision still
    sits right after the sample that triggered it."""
    rid = st["rollout_id"]
    if not rid: return
    mine = logged_events(rid)
    have = {e["stage"] for e in mine if e.get("type") == "stage"}
    for k in range(1, (st["stage"] or 0) + 1):
        if k not in have: event({"type": "stage", "rollout_id": rid, "stage": k, "weights": W(*STAGES[k])})
    types = {e.get("type") for e in mine}
    w = st["window"] or {"green_requests": 0, "green_errors": 0, "error_rate": None}
    if st["state"] == "aborted" and "aborted" not in types:
        event({"type": "aborted", "rollout_id": rid, "reason": st["abort_reason"], "green_requests": w["green_requests"],
               "green_errors": w["green_errors"], "error_rate": w["error_rate"]})
    if st["state"] == "promoted" and "promoted" not in types:
        event({"type": "promoted", "rollout_id": rid})
